await page.routeWebSocket('**/ws/coding/terminals/*', socket => {
  const token = new URL(socket.url()).pathname.split('/').at(-1), ticket = tickets.get(token)
  if (!ticket) { void socket.close({ code: 1008 }); return }
  tickets.delete(token)
  const terminal = terminals.get(ticket.id)
  let after = ticket.after, pending = false
  const flush = () => {
    if (pending || !terminals.has(ticket.id)) return
    if (terminal.bytes.length > after) {
      pending = true
      socket.send(JSON.stringify({ type: 'output', offset: terminal.bytes.length, reset: false }))
      socket.send(terminal.bytes.subarray(after))
    }
  }
  if (!sockets.has(ticket.id)) sockets.set(ticket.id, new Set())
  sockets.get(ticket.id).add(socket)
  socket.onClose(() => { sockets.get(ticket.id)?.delete(socket) })
  socket.onMessage(data => {
    const message = JSON.parse(String(data)); socketMessages.push({ id: ticket.id, ...message })
    if (message.type === 'ack') { after = message.offset; pending = false; flush() }
    if (message.type === 'input') { terminal.bytes = Buffer.concat([terminal.bytes, Buffer.from(message.data)]); flush() }
  })
  flush()
})
