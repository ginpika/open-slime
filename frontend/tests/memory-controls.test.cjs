const { test } = require('node:test')
const assert = require('node:assert/strict')
const { join } = require('node:path')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const build = process.env.MEMORY_BUILD_ROOT
const { filterSelectOptions, nextSelectValue, selectPosition } = require(join(build, 'components/selectModel.js'))
const { Select } = require(join(build, 'components/formKit.js'))
const { Button } = require(join(build, 'components/ui.js'))
const choices = [{ value: '', label: '全部 Agent' }, { value: 'designer-id', label: '设计 Agent' }, { value: 'db-id', label: 'Database Agent' }]
test('长目录可按名称或 ID 搜索，忽略大小写与首尾空白', () => {
  assert.deepEqual(filterSelectOptions(choices, ' database '), [choices[2]])
  assert.deepEqual(filterSelectOptions(choices, 'DESIGNER-ID'), [choices[1]])
  assert.equal(filterSelectOptions(choices, '没有这个名字').length, 0)
})
test('键盘在首尾循环，Home / End 定位边界，空目录不会出错', () => {
  assert.equal(nextSelectValue(choices, 'db-id', 'ArrowDown'), '')
  assert.equal(nextSelectValue(choices, '', 'ArrowUp'), 'db-id')
  assert.equal(nextSelectValue(choices, 'designer-id', 'Home'), '')
  assert.equal(nextSelectValue(choices, 'designer-id', 'End'), 'db-id')
  assert.equal(nextSelectValue([], '', 'ArrowDown'), '')
})
test('弹层在窄视口保持边距、空间不足时向上展开', () => {
  const popup = selectPosition({ left: 260, top: 480, bottom: 520, width: 400 }, { width: 320, height: 568 })
  assert.equal(popup.above, true)
  assert.ok(popup.left >= 8 && popup.left + popup.width <= 312)
  assert.ok(popup.top - popup.maxHeight >= 8)
  const small = selectPosition({ left: 16, top: 70, bottom: 105, width: 190 }, { width: 320, height: 180 })
  assert.ok(small.top + small.maxHeight <= 172)
})
test('旧 formKit 出口仍可用；选择器有标签、禁用状态和按钮类型', () => {
  const html = renderToStaticMarkup(React.createElement(Select, { label: '观察 Agent', value: 'db-id', options: choices, onChange() {}, disabled: true }))
  assert.match(html, /role="combobox"/)
  assert.match(html, /aria-label="观察 Agent"/)
  assert.match(html, /aria-expanded="false"/)
  assert.match(html, /type="button"/)
  assert.match(html, /disabled=""/)
  assert.match(html, /Database Agent/)
  assert.doesNotMatch(html, /<select/)
})
test('共享按钮带有 ui-btn 基底，普通动作不会隐式提交表单', () => {
  const html = renderToStaticMarkup(React.createElement(Button, { variant: 'danger', size: 'sm' }, '遗忘'))
  assert.match(html, /ui-btn ui-btn--danger/)
  assert.match(html, /ui-btn--sm/)
  assert.match(html, /type="button"/)
  const submit = renderToStaticMarkup(React.createElement(Button, { type: 'submit' }, '确认'))
  assert.match(submit, /type="submit"/)
})
