import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'

const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { createElement } = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const { CirclePlay, UserRound, Mail, Info, Minus, Square, Copy, X } = require('lucide-react')
const { version } = require('lucide-react/package.json')
const icons = { launch: CirclePlay, user: UserRound, mail: Mail, about: Info, minimize: Minus, maximize: Square, restore: Copy, close: X }

// 启动页是无构建器的静态 HTML；生成并提交本地资源，运行时无需 React 或网络。
const symbols = Object.entries(icons).map(([name, Icon]) => {
  const svg = renderToStaticMarkup(createElement(Icon))
  const body = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'))
  return `<symbol id="${name}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${body}</g></symbol>`
})
writeFileSync(new URL('../desktop/ui/lucide.svg', import.meta.url), `<!-- Generated by scripts/sync-desktop-icons.mjs from lucide-react ${version}. See lucide.LICENSE.txt. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`)
writeFileSync(new URL('../desktop/ui/lucide.LICENSE.txt', import.meta.url), readFileSync(require.resolve('lucide-react/LICENSE')))
console.log(`Synced ${symbols.length} desktop icons from Lucide ${version}.`)
